const assert = require('assert');
const fs = require('fs');
const path = require('path');
const root = path.resolve(__dirname, '..');
const read = file => fs.readFileSync(path.join(root, file), 'utf8');
const base = read('frontend/store/base.html');
const home = read('frontend/store/index.html');
const detail = read('frontend/store/product_detail.html');
assert(base.includes('id="cartBtn"'), 'carrinho não aparece no header');
assert(base.includes('mercadopago.com/v2/security.js'), 'proteção do checkout não foi reativada');
assert(home.includes('Ver Carrinho'), 'home sem acesso ao carrinho');
assert(detail.includes('addToCartCurrent()'), 'detalhe sem ação de adicionar ao carrinho');
assert(detail.includes('buyNow()'), 'detalhe sem ação de compra imediata');
console.log('store online purchase mode: ok');
